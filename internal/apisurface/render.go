package apisurface

import "strings"

// Render produces the committed manifest: a header that explains the format
// and records the stability tiers, then one line per API element, sorted.
//
// The rendering lives here rather than in the test because the format is part
// of what this package is for. A reviewer reads the diff of this file to
// decide whether a change is additive or a break, so the header has to say how
// to do that, and the tier table has to be generated from the Go table in
// tiers.go — a hand-written copy of it in the manifest would be stale within
// the week, and this repo has the scars to prove it.
func Render(entries []Entry) string {
	var b strings.Builder
	b.WriteString(`# The public API surface of github.com/doug/gophics.
# Generated by internal/apisurface; regenerate with GOPHICS_UPDATE_API=1 go test ./internal/apisurface
#
# One line per API element:
#
#     <package>.<Name>[.<Member>] <kind> <signature>
#
# kind is one of: type alias field method ifacemethod func const var
#
# The name and the kind are the key and the file is sorted by it, so the diff
# reads directly:
#
#   a lone +                      additive; a v1 package may do this
#   a lone -                      a removal: a break
#   a -/+ pair on the same key    the signature moved: a break
#   a + on an ifacemethod         an interface grew a method: breaks implementers
#
# Conventions that keep that true:
#
#   Parameter names are omitted — Go has no keyword arguments, so a rename
#   cannot break a caller, and recording names would make a rename look
#   identical to a type change.
#
#   A method carries its receiver as its first parameter, the method
#   expression form, so moving a method to a pointer receiver — which drops it
#   from the value's method set — is visible.
#
#   An interface records its whole method set, embedded methods included,
#   because that is what an implementer has to provide.
#
#   A constant records its value. For theme.FontBold the value is the API, and
#   for an iota block it is whatever has been persisted or sent.
#
# Excludes internal/, examples/, cmd/, docs/, skills/ and shell/mobile
# (a gomobile binding, versioned with the host app). See the package doc.
#
# Stability tiers, proposed for v1 — see README.md for the reasoning. The
# module is pre-1.0; v1 here means "proposed to freeze", not "frozen".
`)
	byTier := ByTier()
	for _, t := range []Tier{TierV1, TierUnstable} {
		for _, pkg := range byTier[t] {
			b.WriteString("# tier " + string(t) + " " + pkg + "\n")
		}
	}
	for _, e := range entries {
		b.WriteString(string(e))
		b.WriteByte('\n')
	}
	return b.String()
}
