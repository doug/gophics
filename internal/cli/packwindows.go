// Windows packaging: a staged directory, version metadata, and installer
// sources.
//
// The file is not called pack_windows.go on purpose — that suffix is a build
// constraint, and this code has to compile on the Mac that cross-packages for
// Windows. Same for packlinux.go.
//
// Windows has no bundle. An application is an .exe plus whatever sits beside
// it, so the deliverable is a directory that can be zipped, copied, or fed to
// an installer compiler. What a user notices is the metadata: an .exe with no
// version resource shows "Unknown publisher" in the SmartScreen dialog, blank
// fields in Properties, and the generic icon everywhere. That resource is the
// one thing here that needs a compiler, so it is attempted with whatever is
// installed and skipped with an explanation when nothing is.
//
// The installer sources — WiX and NSIS — are generated rather than compiled,
// because neither compiler runs on macOS out of the box. They are complete
// sources: Start menu shortcut, uninstaller, Add/Remove Programs entry, and an
// upgrade code derived from the bundle identifier so version 2 replaces
// version 1 instead of installing beside it.

func (p *packer) packWindows() ([]string, error) {
	out := p.outDir()
	stage := filepath.Join(out, p.o.name)
	installer := filepath.Join(out, "installer")
	for _, d := range []string{stage, installer} {
		if err := os.RemoveAll(d); err != nil {
			return nil, err
		}
		if err := os.MkdirAll(d, 0o755); err != nil {
			return nil, err
		}
	}
	exe := exeName("windows", p.slug)

	// The resources are written before the build: the version resource has to
	// be compiled into an object the linker picks up, so it cannot be added
	// afterwards.
	manifestName := exe + ".manifest"
	if _, err := writeFileIn(stage, manifestName, []byte(p.windowsManifest()), 0o644); err != nil {
		return nil, err
	}
	icoName := ""
	if p.icon != nil {
		icoName = p.slug + ".ico"
		if err := p.icon.writeICO(filepath.Join(stage, icoName)); err != nil {
			return nil, err
		}
		if err := copyFile(filepath.Join(stage, icoName), filepath.Join(installer, icoName)); err != nil {
			return nil, err
		}
	}
	if err := copyFile(filepath.Join(stage, manifestName), filepath.Join(installer, manifestName)); err != nil {
		return nil, err
	}
	rc := filepath.Join(installer, "resources.rc")
	if err := os.WriteFile(rc, []byte(p.windowsRC(icoName, manifestName)), 0o644); err != nil {
		return nil, err
	}

	// Compiled into the package directory, where the go tool looks for .syso
	// files, and removed again afterwards: a stray resource object left in
	// someone's source tree would silently attach this version number to
	// every later build of the app.
	for _, syso := range p.embedWindowsResources(installer, rc) {
		defer os.Remove(syso)
	}

	p.step("building %s (%s)", exe, p.o.goarch)
	if err := p.buildBinary(filepath.Join(stage, exe), p.o.goarch); err != nil {
		return nil, err
	}

	artifacts := []string{stage}
	zipPath := filepath.Join(out, p.artifactName()+".zip")
	p.step("archiving %s", filepath.Base(zipPath))
	if err := writeZip(zipPath, stage); err != nil {
		return nil, err
	}
	artifacts = append(artifacts, zipPath)

	wxs := filepath.Join(installer, p.o.name+".wxs")
	if err := os.WriteFile(wxs, []byte(p.wixSource(exe, icoName)), 0o644); err != nil {
		return nil, err
	}
	nsi := filepath.Join(installer, p.o.name+".nsi")
	if err := os.WriteFile(nsi, []byte(p.nsisSource(exe, icoName, manifestName)), 0o644); err != nil {
		return nil, err
	}
	artifacts = append(artifacts, wxs, nsi, rc)
	artifacts = append(artifacts, p.buildWindowsInstallers(installer, wxs, nsi)...)
	return artifacts, nil
}

// windowsManifest is the side-by-side application manifest.
//
// Its job is DPI awareness. Without a manifest Windows lies to the process
// about the screen: it reports 96 DPI, renders the window at that size and
// scales the result up, so a gophics app — which asks the platform for the
// real scale factor and lays out in logical pixels — draws a sharp frame that
// the compositor then blurs. PerMonitorV2 is the declaration that the app
// handles scale changes itself, which it does: moving the window between a
// Retina and a 1x display is a scale change the shell already propagates.
//
// It is written beside the .exe as well as compiled in, because the external
// file is read when no resource compiler was available to embed it. Windows
// prefers the embedded one when both exist, and they say the same thing.
func (p *packer) windowsManifest() string {
	return fmt.Sprintf(`<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<!-- Generated by gophics package. -->
<assembly xmlns="urn:schemas-microsoft-com:asm.v1" manifestVersion="1.0">
  <assemblyIdentity type="win32" name="%s" version="%s" processorArchitecture="*"/>
  <description>%s</description>
  <trustInfo xmlns="urn:schemas-microsoft-com:asm.v3">
    <security>
      <requestedPrivileges>
        <!-- asInvoker: the app writes only to the user's own data, so it must
             never prompt for elevation. A packaged app that asks for admin on
             every launch is one users stop launching. -->
        <requestedExecutionLevel level="asInvoker" uiAccess="false"/>
      </requestedPrivileges>
    </security>
  </trustInfo>
  <application xmlns="urn:schemas-microsoft-com:asm.v3">
    <windowsSettings>
      <dpiAwareness xmlns="http://schemas.microsoft.com/SMI/2016/WindowsSettings">PerMonitorV2</dpiAwareness>
      <!-- The pre-Windows-10 spelling, still read by 8.1 and by some
           remote-desktop paths. -->
      <dpiAware xmlns="http://schemas.microsoft.com/SMI/2005/WindowsSettings">true/pm</dpiAware>
      <!-- UTF-8 as the process code page, so the ANSI side of the Win32 API
           agrees with Go's strings instead of mangling non-ASCII paths. -->
      <activeCodePage xmlns="http://schemas.microsoft.com/SMI/2019/WindowsSettings">UTF-8</activeCodePage>
    </windowsSettings>
  </application>
  <compatibility xmlns="urn:schemas-microsoft-com:compatibility.v1">
    <application>
      <!-- Windows 10 and 11. Without a supportedOS entry the OS applies
           compatibility shims meant for Vista-era software. -->
      <supportedOS Id="{8e0f7a12-bfb3-4fe8-b9a5-48fd50a15a9a}"/>
    </application>
  </compatibility>
</assembly>
`, xmlEscape(p.o.id), fourPart(p.o.version), xmlEscape(p.o.comment))
}

// windowsRC is the resource script: the icon, the manifest and VERSIONINFO.
//
// No #include, so it compiles with a bare windres that has no Windows SDK
// headers beside it — the numeric resource types are stable and documented
// (24 is RT_MANIFEST, and resource id 1 is the one a process's own manifest
// must use).
func (p *packer) windowsRC(ico, manifest string) string {
	var b strings.Builder
	b.WriteString("// Generated by gophics package. Compile into a linkable object with\n")
	b.WriteString("//   windres -i resources.rc -O coff -o rsrc_windows_amd64.syso\n")
	b.WriteString("// and place it in the main package's directory; the go tool links any\n")
	b.WriteString("// .syso it finds there.\n\n")
	if ico != "" {
		// Id 1 is what Explorer shows for the file: the lowest-numbered icon
		// resource is the application icon.
		fmt.Fprintf(&b, "1 ICON %q\n", ico)
	}
	fmt.Fprintf(&b, "1 24 %q // RT_MANIFEST\n\n", manifest)
	four := strings.ReplaceAll(fourPart(p.o.version), ".", ",")
	b.WriteString("1 VERSIONINFO\n")
	fmt.Fprintf(&b, "FILEVERSION %s\n", four)
	fmt.Fprintf(&b, "PRODUCTVERSION %s\n", four)
	b.WriteString("FILEFLAGSMASK 0x3fL\n")
	b.WriteString("FILEFLAGS 0x0L\n")
	b.WriteString("FILEOS 0x40004L // VOS_NT_WINDOWS32\n")
	b.WriteString("FILETYPE 0x1L    // VFT_APP\n")
	b.WriteString("FILESUBTYPE 0x0L\n")
	b.WriteString("BEGIN\n")
	b.WriteString("  BLOCK \"StringFileInfo\"\n  BEGIN\n")
	// 040904b0: US English, Unicode. The block name has to match the
	// Translation value below or Explorer reads no strings at all.
	b.WriteString("    BLOCK \"040904b0\"\n    BEGIN\n")
	for _, kv := range [][2]string{
		{"CompanyName", p.o.publisher},
		{"FileDescription", p.o.comment},
		{"FileVersion", p.o.version},
		{"InternalName", p.slug},
		{"LegalCopyright", p.o.copyright},
		{"OriginalFilename", exeName("windows", p.slug)},
		{"ProductName", p.o.name},
		{"ProductVersion", p.o.version},
	} {
		if kv[1] == "" {
			continue
		}
		fmt.Fprintf(&b, "      VALUE %q, %q\n", kv[0], kv[1])
	}
	b.WriteString("    END\n  END\n")
	b.WriteString("  BLOCK \"VarFileInfo\"\n  BEGIN\n")
	b.WriteString("    VALUE \"Translation\", 0x409, 1200\n")
	b.WriteString("  END\nEND\n")
	return b.String()
}

// embedWindowsResources compiles resources.rc into a resource object in the
// app's own package directory — the only place the go tool looks for one — and
// returns the files it created, so the caller can delete them after the link.
//
// Two compilers are tried. go-winres is a pure-Go tool that handles every
// architecture including arm64, and windres comes with mingw-w64 (brew install
// mingw-w64) but has no arm64 target. Neither is a dependency: without one the
// .exe links without a version resource, which costs it the Properties dialog
// and the Explorer icon and nothing else. The .rc is left behind either way so
// a Windows machine, or a CI job that has a compiler, can finish the job.
//
// What was created is discovered by comparing the directory before and after,
// not assumed from the name handed to the compiler. This writes into someone
// else's source tree, and a file left behind there would silently attach this
// run's version number to every later build of the app.
func (p *packer) embedWindowsResources(installer, rc string) []string {
	before, err := filepath.Glob(filepath.Join(p.dir, "*.syso"))
	if err != nil {
		p.note("could not look for resource objects in %s (%v); none embedded.", p.dir, err)
		return nil
	}
	// Never alongside a resource object the app already has: two VERSIONINFO
	// resources in one binary is a link error, and the app's own is the one it
	// means to ship.
	if len(before) > 0 {
		p.note("%s already carries %s, so the generated version resource is left out; "+
			"the app's own resource wins.", p.dir, filepath.Base(before[0]))
		return nil
	}
	created := func() []string {
		after, _ := filepath.Glob(filepath.Join(p.dir, "*.syso"))
		return after
	}
	syso := filepath.Join(p.dir, "gophics_rsrc_windows_"+p.o.goarch+".syso")

	if have("go-winres") {
		args := []string{"simply",
			"--arch", p.o.goarch,
			"--out", "gophics_rsrc",
			"--manifest", "gui",
			"--file-version", fourPart(p.o.version),
			"--product-version", p.o.version,
			"--product-name", p.o.name,
		}
		if p.o.comment != "" {
			args = append(args, "--file-description", p.o.comment)
		}
		if p.o.copyright != "" {
			args = append(args, "--copyright", p.o.copyright)
		}
		if p.icon != nil {
			args = append(args, "--icon", filepath.Join(installer, p.slug+".ico"))
		}
		p.step("embedding version resource with go-winres")
		if err := run(p.dir, nil, "go-winres", args...); err != nil {
			p.note("go-winres failed; the .exe links without a version resource.")
		}
		return created()
	}

	wr := windresBinary()
	if wr == "" {
		p.note("no version resource embedded: neither go-winres nor windres is installed, " +
			"so Explorer shows the generic icon and an empty Properties dialog.\n" +
			"  Either of these fixes it, then re-run:\n" +
			"    go install github.com/tc-hib/go-winres@latest   # any architecture, pure Go\n" +
			"    brew install mingw-w64                          # provides windres (x86 only)\n" +
			"  installer/resources.rc holds the resource either way.")
		return nil
	}
	target := windresTarget(p.o.goarch)
	if target == "" {
		p.note("windres has no %s target, so no version resource was embedded; "+
			"go-winres (go install github.com/tc-hib/go-winres@latest) does support it.", p.o.goarch)
		return nil
	}
	p.step("embedding version resource with %s", filepath.Base(wr))
	if err := run(installer, nil, wr,
		"-i", filepath.Base(rc), "-O", "coff", "--target="+target, "-o", syso); err != nil {
		p.note("%s failed; the .exe links without a version resource.", filepath.Base(wr))
	}
	return created()
}

// windresBinary finds a windres, under its own name or the mingw-w64 prefixed
// names Homebrew and the Linux distributions install.
func windresBinary() string {
	for _, n := range []string{
		"windres",
		"x86_64-w64-mingw32-windres",
		"i686-w64-mingw32-windres",
	} {
		if p, err := exec.LookPath(n); err == nil {
			return p
		}
	}
	return ""
}

// windresTarget is the BFD target name for a GOARCH, or "" when windres cannot
// produce an object for it.
func windresTarget(goarch string) string {
	switch goarch {
	case "amd64":
		return "pe-x86-64"
	case "386":
		return "pe-i386"
	default:
		return "" // arm64: binutils has no PE/COFF ARM64 target
	}
}

// wixSource is a WiX v4/v5 installer source.
//
// v4 syntax rather than v3's: `wix build` is a cross-platform dotnet tool, so
// this is the one of the two that a developer on a Mac or on Linux can
// actually compile. The GUIDs are derived from the bundle identifier (see
// uuidV5), which is what makes an upgrade replace the installed version — a
// generated installer with a fresh UpgradeCode each build installs version 2
// beside version 1 and leaves the user with two Start menu entries.
func (p *packer) wixSource(exe, ico string) string {
	ns := "gophics.wix." + p.o.id
	var icoBits, iconComponent string
	if ico != "" {
		icoBits = fmt.Sprintf("\n    <Icon Id=\"AppIcon\" SourceFile=\"%s\"/>\n"+
			"    <Property Id=\"ARPPRODUCTICON\" Value=\"AppIcon\"/>", ico)
		iconComponent = fmt.Sprintf(`
      <Component Directory="INSTALLFOLDER" Guid="%s">
        <File Source="..\%s\%s"/>
      </Component>`, uuidV5(ns, "component.icon"), p.o.name, ico)
	}
	shortcutIcon := ""
	if ico != "" {
		shortcutIcon = ` Icon="AppIcon"`
	}
	return fmt.Sprintf(`<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by gophics package. Build it with the WiX toolset (v4 or newer):

       dotnet tool install -g wix
       wix build %s.wxs -arch %s -o %s.msi

     The file paths are relative to this directory, so build it from here.
     (The install command is spelled with the short flag on purpose: a double
     hyphen cannot appear inside an XML comment, and this file has to parse.)
-->
<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">
  <Package Name="%s" Manufacturer="%s" Version="%s" UpgradeCode="%s"
           Language="1033" Scope="perMachine" Compressed="yes">
    <SummaryInformation Description="%s"/>
    <!-- Replace rather than install beside: without this an upgrade leaves
         both versions installed and two entries in Add/Remove Programs. -->
    <MajorUpgrade DowngradeErrorMessage="A newer version of [ProductName] is already installed."/>
    <MediaTemplate EmbedCab="yes"/>

    <StandardDirectory Id="ProgramFiles6432Folder">
      <Directory Id="INSTALLFOLDER" Name="%s"/>
    </StandardDirectory>
    <StandardDirectory Id="ProgramMenuFolder">
      <Directory Id="AppMenuFolder" Name="%s"/>
    </StandardDirectory>

    <Feature Id="Main" Title="%s" Level="1">
      <ComponentGroupRef Id="AppFiles"/>
    </Feature>

    <ComponentGroup Id="AppFiles">
      <Component Directory="INSTALLFOLDER" Guid="%s">
        <File Id="AppExe" Source="..\%s\%s" KeyPath="yes"/>
      </Component>%s
      <Component Directory="AppMenuFolder" Guid="%s">
        <Shortcut Id="AppShortcut" Name="%s" Description="%s"
                  Target="[INSTALLFOLDER]%s" WorkingDirectory="INSTALLFOLDER"%s/>
        <RemoveFolder Id="RemoveAppMenuFolder" On="uninstall"/>
        <!-- A per-user registry value as the KeyPath, because a Start menu
             shortcut in a per-machine install has no per-user file MSI can
             track and the component would be reported as broken. -->
        <RegistryValue Root="HKCU" Key="Software\%s\%s" Name="installed"
                       Type="integer" Value="1" KeyPath="yes"/>
      </Component>
    </ComponentGroup>%s
  </Package>
</Wix>
`,
		p.o.name, wixArch(p.o.goarch), p.artifactName(),
		xmlEscape(p.o.name), xmlEscape(p.o.publisher), fourPart(p.o.version), uuidV5(ns, "upgrade"),
		xmlEscape(p.o.comment),
		xmlEscape(p.o.name), xmlEscape(p.o.name), xmlEscape(p.o.name),
		uuidV5(ns, "component.exe"), p.o.name, exe, iconComponent,
		uuidV5(ns, "component.shortcut"),
		xmlEscape(p.o.name), xmlEscape(p.o.comment), exe, shortcutIcon,
		xmlEscape(p.o.publisher), xmlEscape(p.o.name),
		icoBits)
}

// wixArch is the -arch value for a GOARCH.
func wixArch(goarch string) string {
	switch goarch {
	case "386":
		return "x86"
	case "arm64":
		return "arm64"
	default:
		return "x64"
	}
}

// nsisSource is an NSIS installer script.
//
// Generated alongside the WiX source rather than instead of it, because the
// two are not interchangeable: an MSI is what a corporate deployment tool
// expects, and an NSIS .exe is what an individual downloads. makensis also
// runs on macOS and Linux (brew install makensis), which makes it the one
// installer a developer here can actually build and test.
func (p *packer) nsisSource(exe, ico, manifest string) string {
	var b strings.Builder
	fmt.Fprintf(&b, `; Generated by gophics package. Build it with
;   makensis %s.nsi
; which runs on macOS and Linux too (brew install makensis, apt install nsis).

Unicode True
Name "%s"
OutFile "..\%s-setup.exe"
InstallDir "$PROGRAMFILES64\%s"
InstallDirRegKey HKLM "Software\%s" "InstallDir"
; An installer that writes to Program Files needs elevation, and asking for it
; up front is better than failing halfway through a copy.
RequestExecutionLevel admin
SetCompressor /SOLID lzma

VIProductVersion "%s"
VIAddVersionKey "ProductName" "%s"
VIAddVersionKey "ProductVersion" "%s"
VIAddVersionKey "FileVersion" "%s"
VIAddVersionKey "FileDescription" "%s installer"
`,
		p.o.name, p.o.name, p.artifactName(), p.o.name, p.o.name,
		fourPart(p.o.version), p.o.name, p.o.version, fourPart(p.o.version), p.o.name)
	if p.o.publisher != "" {
		fmt.Fprintf(&b, "VIAddVersionKey \"CompanyName\" %q\n", p.o.publisher)
	}
	if p.o.copyright != "" {
		fmt.Fprintf(&b, "VIAddVersionKey \"LegalCopyright\" %q\n", p.o.copyright)
	}
	if ico != "" {
		fmt.Fprintf(&b, "Icon \"%s\"\nUninstallIcon \"%s\"\n", ico, ico)
	}
	fmt.Fprintf(&b, `
!define UNINSTKEY "Software\Microsoft\Windows\CurrentVersion\Uninstall\%s"

Page directory
Page instfiles
UninstPage uninstConfirm
UninstPage instfiles

Section "Install"
	SetOutPath "$INSTDIR"
	File "..\%s\%s"
	File "..\%s\%s"
`, p.o.id, p.o.name, exe, p.o.name, manifest)
	if ico != "" {
		fmt.Fprintf(&b, "\tFile \"..\\%s\\%s\"\n", p.o.name, ico)
	}
	shortcutIcon := ""
	if ico != "" {
		shortcutIcon = fmt.Sprintf(` "" "$INSTDIR\%s"`, ico)
	}
	fmt.Fprintf(&b, `
	CreateDirectory "$SMPROGRAMS\%s"
	CreateShortcut "$SMPROGRAMS\%s\%s.lnk" "$INSTDIR\%s"%s

	WriteRegStr HKLM "Software\%s" "InstallDir" "$INSTDIR"
	; The Add/Remove Programs entry. Without DisplayName and UninstallString
	; the app is installed and cannot be uninstalled from Settings.
	WriteRegStr HKLM "${UNINSTKEY}" "DisplayName" "%s"
	WriteRegStr HKLM "${UNINSTKEY}" "DisplayVersion" "%s"
	WriteRegStr HKLM "${UNINSTKEY}" "UninstallString" '"$INSTDIR\uninstall.exe"'
	WriteRegStr HKLM "${UNINSTKEY}" "InstallLocation" "$INSTDIR"
	WriteRegDWORD HKLM "${UNINSTKEY}" "NoModify" 1
	WriteRegDWORD HKLM "${UNINSTKEY}" "NoRepair" 1
`,
		p.o.name, p.o.name, p.o.name, exe, shortcutIcon,
		p.o.name, p.o.name, p.o.version)
	if p.o.publisher != "" {
		fmt.Fprintf(&b, "\tWriteRegStr HKLM \"${UNINSTKEY}\" \"Publisher\" %q\n", p.o.publisher)
	}
	if ico != "" {
		fmt.Fprintf(&b, "\tWriteRegStr HKLM \"${UNINSTKEY}\" \"DisplayIcon\" \"$INSTDIR\\%s\"\n", ico)
	}
	fmt.Fprintf(&b, `	WriteUninstaller "$INSTDIR\uninstall.exe"
SectionEnd

Section "Uninstall"
	Delete "$INSTDIR\%s"
	Delete "$INSTDIR\%s"
`, exe, manifest)
	if ico != "" {
		fmt.Fprintf(&b, "\tDelete \"$INSTDIR\\%s\"\n", ico)
	}
	fmt.Fprintf(&b, `	Delete "$INSTDIR\uninstall.exe"
	RMDir "$INSTDIR"
	Delete "$SMPROGRAMS\%s\%s.lnk"
	RMDir "$SMPROGRAMS\%s"
	DeleteRegKey HKLM "${UNINSTKEY}"
	DeleteRegKey HKLM "Software\%s"
SectionEnd
`, p.o.name, p.o.name, p.o.name, p.o.name)
	return b.String()
}

// buildWindowsInstallers compiles whichever installer sources it has a
// compiler for, and says what it would have taken otherwise.
//
// Best effort on purpose: the sources are the deliverable, and a packaging run
// on a machine with neither compiler must still succeed. A compiler that is
// present and fails is reported, not fatal — the staged directory and the zip
// are already written and are what most people will ship.
func (p *packer) buildWindowsInstallers(dir, wxs, nsi string) []string {
	var built []string
	if have("makensis") {
		p.step("building %s-setup.exe with makensis", p.artifactName())
		if err := run(dir, nil, "makensis", filepath.Base(nsi)); err != nil {
			p.note("makensis failed (%v); %s is still there to build by hand.", err, filepath.Base(nsi))
		} else {
			built = append(built, filepath.Join(p.outDir(), p.artifactName()+"-setup.exe"))
		}
	} else {
		p.note("no NSIS installer built: makensis is not installed (brew install makensis, "+
			"apt install nsis). The source is %s.", filepath.Base(nsi))
	}
	if have("wix") {
		msi := p.artifactName() + ".msi"
		p.step("building %s with wix", msi)
		if err := run(dir, nil, "wix", "build", filepath.Base(wxs),
			"-arch", wixArch(p.o.goarch), "-o", filepath.Join("..", msi)); err != nil {
			p.note("wix build failed (%v); %s is still there to build by hand.", err, filepath.Base(wxs))
		} else {
			built = append(built, filepath.Join(p.outDir(), msi))
		}
	} else {
		p.note("no MSI built: the WiX toolset is not installed "+
			"(dotnet tool install --global wix). The source is %s.", filepath.Base(wxs))
	}
	return built
}
